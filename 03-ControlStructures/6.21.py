user_coin = int(input('Enter the amount in PLN: '))
pln_5 = 0
pln_2 = 0
pln_1 = 0

while user_coin >= 5:
    user_coin - 5 == 0
    user_coin -= 5
    pln_5 += 1

while user_coin >= 2:
    user_coin - 2 == 0
    user_coin -= 2
    pln_2 += 1

while user_coin >= 1:
    user_coin - 1 == 0
    user_coin -= 1
    pln_1 += 1

print(f'5 PLN coins: {pln_5}, 2 PLN coins: {pln_2}, 1 PLN coins: {pln_1}')